@dataclass(frozen=True)
class PistonTargets:
    """FLASH-measured piston + ambient state, as written by
    ``scripts/flash_piston_profile.py`` and recorded in the run spec's
    ``flash_target:`` block.

    The ambient quantities are taken *just ahead of the piston front*, not at the
    FLASH initial condition: the chamber plasma rarefies substantially over the first
    few ns, and it is the state the piston actually drives into that sets M_A and
    beta.  Same "self-consistent dump" discipline the OSIRIS side follows.
    """

    n_amb_per_m3: float
    b_amb_tesla: float
    te_amb_ev: float
    ti_amb_ev: float
    n_piston_drive_per_m3: float
    """Piston electron density just BEHIND the front — the density that drives the
    shock.  Deliberately not the profile's global peak: on these line-outs that peak
    sits in the dense stagnated material next to the target, ~40x above the material
    actually arriving at the front, and using it overstates the contrast accordingly."""
    v_front_ms: float
    l_piston_m: float
    """Piston density e-folding length into the upstream."""
    r_spot_m: float
    """Piston transverse half-width, i.e. the laser-spot scale."""
    t_window_s: float
    """Duration of FLASH evolution the deck should reproduce."""
    a_amb: float = 26.98
    """Ambient ion mass number (Al foam chamber)."""
    z_amb: float = 13.0
    a_piston: float = 28.0855
    """Piston ion mass number (Si target)."""
    z_piston: float = 14.0
    gamma: float = GAMMA_DEFAULT
    source: str = ""
    """Provenance string, echoed into the generated deck's header."""

    @property
    def m_i_amb_kg(self) -> float:
        return self.a_amb * M_P_KG

    @property
    def n_i_amb_per_m3(self) -> float:
        """Ambient ion density, from quasineutrality n_e = Z n_i."""
        return self.n_amb_per_m3 / self.z_amb

    @property
    def v_alfven_ms(self) -> float:
        return alfven_speed_ms(self.b_amb_tesla, self.n_i_amb_per_m3, self.m_i_amb_kg)

    @property
    def c_s_ms(self) -> float:
        """Ambient ion-acoustic speed."""
        return ion_acoustic_speed_ms(self.te_amb_ev, self.ti_amb_ev, self.m_i_amb_kg,
                                     charge_state=self.z_amb, gamma_ion=self.gamma)

    @property
    def v_fast_ms(self) -> float:
        """Ambient fast-magnetosonic speed sqrt(v_A^2 + c_s^2)."""
        return float(np.hypot(self.v_alfven_ms, self.c_s_ms))

    @property
    def mach_alfven(self) -> float:
        return _safe_ratio(self.v_front_ms, self.v_alfven_ms)

    @property
    def mach_magnetosonic(self) -> float:
        return _safe_ratio(self.v_front_ms, self.v_fast_ms)

    @property
    def beta_e(self) -> float:
        return plasma_beta(self.n_amb_per_m3, self.te_amb_ev, self.b_amb_tesla)

    @property
    def beta_i(self) -> float:
        return plasma_beta(self.n_i_amb_per_m3, self.ti_amb_ev, self.b_amb_tesla)

    @property
    def contrast(self) -> float:
        """Piston/ambient electron-density contrast."""
        return float(self.n_piston_drive_per_m3 / self.n_amb_per_m3)

    @property
    def d_i_m(self) -> float:
        return ion_inertial_length_m(self.n_i_amb_per_m3, self.m_i_amb_kg,
                                     charge_state=self.z_amb)

    @property
    def omega_ci_rad_s(self) -> float:
        return ion_gyrofrequency_rad_s(self.b_amb_tesla, self.m_i_amb_kg,
                                       charge_state=self.z_amb)

    @property
    def gyroperiod_s(self) -> float:
        omega_ci = self.omega_ci_rad_s
        if not (np.isfinite(omega_ci) and omega_ci > 0.0):
            return float("nan")
        return float(2.0 * np.pi / omega_ci)

    @property
    def l_piston_di(self) -> float:
        return float(self.l_piston_m / self.d_i_m)

    @property
    def r_spot_di(self) -> float:
        return float(self.r_spot_m / self.d_i_m)

    @property
    def t_window_gyro(self) -> float:
        """Requested FLASH window in ambient ion gyroperiods."""
        return float(self.t_window_s / self.gyroperiod_s)

    def invariants(self) -> dict[str, float]:
        """The dimensionless numbers the reduced-mass deck is built to preserve."""
        return {
            "M_A": self.mach_alfven,
            "M_ms": self.mach_magnetosonic,
            "beta_e": self.beta_e,
            "beta_i": self.beta_i,
            "contrast": self.contrast,
            "r_spot/d_i": self.r_spot_di,
            "t_run/T_ci": self.t_window_gyro,
        }


