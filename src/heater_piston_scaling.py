"""heater_piston_scaling.py — map a FLASH piston to a reduced-mass WarpX PIC deck.

The 2D WarpX runs generated by ``init_warpx/gen_heater_deck.py`` do not read FLASH
data.  They *grow* their piston: a dense cold slab is replenished by WarpX's
``TargetInjector`` and heated by ``ParticleHeater``'s momentum-space diffusion (the
PSC / Fox et al. 2018 laser-ablation surrogate), and the heated slab expands as a
self-consistent, kinetically smooth piston into a uniform magnetized ambient.

This module is the bridge: it takes the FLASH-measured piston and ambient state
(:class:`PistonTargets`, produced by ``scripts/flash_piston_profile.py``) and returns
the deck's constants (:class:`ReducedScaling`).

What can and cannot be matched
------------------------------
A full-PIC run of a real 7 T, ~1e24 m^-3, cm-scale, Z=13/14 experiment is not
affordable, so the deck deliberately runs at a reduced ion/electron mass ratio and an
arbitrary reference density.  That fixes *dimensionless* similarity, not absolute
scales.  Held fixed (:meth:`PistonTargets.invariants`):

  * ``M_A``   = v_piston / v_A                 — Alfvenic drive strength
  * ``M_ms``  = v_piston / sqrt(v_A^2 + c_s^2) — super-criticality
  * ``beta_e``, ``beta_i``                     — ambient pressure balance
  * ``n_piston / n_ambient``                   — piston/ambient contrast
  * ``r_spot / d_i``                           — piston transverse geometry
  * ``omega_ci * t_run``                       — gyroperiods simulated

Necessarily broken, and why it is acceptable:

  * ``m_i/m_e`` (1836*A/Z -> ``mass_ratio``).  Compresses the electron/ion scale
    separation so d_e is resolvable; standard practice in this regime.  Consequence:
    ``omega_pe/omega_ci`` and ``v_th,e/c`` are not the experiment's, so electron-scale
    kinetics (Weibel growth rates, electron heating rates) are only qualitative.
  * ``Z`` -> 1.  The heater/injector pair is charge-state agnostic; a single
    hydrogenic ion carries the inertia that sets d_i and the gyroradius.
  * absolute ns / um.  The run lives in ``1/omega_pe`` and ``d_e``;
    :meth:`ReducedScaling.to_ns` / :meth:`ReducedScaling.to_um` convert back through
    the matched ion scales, which is how ``scripts/warpx_heater_compare.py`` puts the
    two codes on one axis.

Stdlib + numpy only, so this is unit-tested in CI alongside the rest of ``src/`` (no
yt, no WarpX, no astropy).  SI throughout; every dimensionful name carries its unit.
"""

from dataclasses import dataclass, field
from typing import Sequence

import numpy as np

C_LIGHT_MS = 2.99792458e8
MU_0 = 4.0e-7 * np.pi
EPSILON_0 = 1.0 / (MU_0 * C_LIGHT_MS**2)
Q_E = 1.602176634e-19
M_E_KG = 9.1093837015e-31
M_P_KG = 1.67262192369e-27

GAMMA_DEFAULT = 5.0 / 3.0

#: ``v_piston = KAPPA_DEFAULT * c_s(theta_e)`` — the expansion-front speed of a heated
#: slab in units of its own ion-acoustic speed.
#:
#: MEASURED, not assumed.  The first 2D run (568x2832, theta_e = 0.04, mass_ratio 100)
#: aimed for 0.050 c and delivered 0.0202 c, i.e. kappa = 1.01 — so the front speed and
#: every quantity derived through it (B0, the ambient temperatures, M_A) were off by 2.5x.
#: The earlier 2.5 came from the classic rarefaction-front result and from reading the
#: validated 1D run's *shock* speed (0.074 c) as if it were the piston contact speed; in
#: 2D, with a finite heating spot, the contact moves at about one c_s.
KAPPA_DEFAULT = 1.01

#: Reference point for :meth:`ReducedScaling.cost_report`: the validated
#: ``heating_operator/run_prod_compare/L0_launch`` job did 2048x4096 cells for 15000
#: steps at 16 macroparticles/cell over 2 domain-filling species pairs, on 4
#: Perlmutter CPU nodes (64 ranks) in 2 h 55 m.
_COST_REF_WORK = (2048.0 * 4096.0) * 16.0 * 2.0 * 15000.0
_COST_REF_NODE_HOURS = 4.0 * (2.0 + 55.0 / 60.0)

#: AMReX blocking factor the cell counts are rounded up to.
BLOCKING_DEFAULT = 8

#: Below this ``lambda_De / dx`` the cold ambient is at risk of numerical (grid) heating.
#: From the OSIRIS dx/ppc convergence scan recorded in CLAUDE.md: the Debye length does
#: NOT have to be resolved, but runs below ~0.03 heated away while 0.1 and 0.3 stayed
#: clean over several gyroperiods.  A cold, low-beta upstream is exactly the case that
#: pushes a heater deck under it, so :func:`derive` checks and warns.
DEBYE_PER_CELL_MIN = 0.03

#: Piston-electron thermal speed (in c) above which the heater's non-relativistic momentum
#: kicks stop reproducing the ``theta_e`` they are meant to impose.  gamma = 1.05 at 0.3.
RELATIVISTIC_VTH_MAX = 0.3

#: Plotfile count a production run should land in.  Below ~10 frames the front trajectory
#: cannot be fitted; above ~200 the I/O throttles the run harder than the physics does
#: (measured: 4.6 GB per dump with raw particles against 0.27 GB of grid fields).  The
#: cadence is set in STEPS, so it has to be rescaled whenever the step count moves —
#: which is what ``heater_spec.validate`` uses this to catch.
PLOTFILE_COUNT_RANGE = (10, 200)


# ---------------------------------------------------------------------------
# Elementary SI plasma quantities
# ---------------------------------------------------------------------------

def plasma_frequency_rad_s(electron_density_per_m3: float) -> float:
    """Electron plasma frequency omega_pe = sqrt(n_e e^2 / (eps0 m_e)) [rad/s]."""
    if electron_density_per_m3 <= 0.0:
        return float("nan")
    return float(np.sqrt(electron_density_per_m3 * Q_E**2 / (EPSILON_0 * M_E_KG)))


def electron_skin_depth_m(electron_density_per_m3: float) -> float:
    """Electron inertial length d_e = c / omega_pe [m]."""
    omega_pe = plasma_frequency_rad_s(electron_density_per_m3)
    if not (np.isfinite(omega_pe) and omega_pe > 0.0):
        return float("nan")
    return float(C_LIGHT_MS / omega_pe)


def alfven_speed_ms(b_tesla: float, ion_density_per_m3: float,
                    ion_mass_kg: float) -> float:
    """Alfven speed v_A = B / sqrt(mu0 n_i m_i) [m/s]."""
    if ion_density_per_m3 <= 0.0 or ion_mass_kg <= 0.0:
        return float("nan")
    return float(abs(b_tesla) / np.sqrt(MU_0 * ion_density_per_m3 * ion_mass_kg))


def ion_acoustic_speed_ms(
    te_ev: float,
    ti_ev: float,
    ion_mass_kg: float,
    charge_state: float = 1.0,
    gamma_electron: float = 1.0,
    gamma_ion: float = GAMMA_DEFAULT,
) -> float:
    """Ion-acoustic speed c_s = sqrt((g_e Z kT_e + g_i kT_i)/m_i) [m/s].

    ``gamma_electron = 1`` (isothermal electrons) is the usual choice for an expanding
    laser plasma; ``gamma_ion = 5/3`` for adiabatic ions.  Negative temperatures are
    clamped to zero so a noisy FLASH cell cannot produce a nan.
    """
    if ion_mass_kg <= 0.0:
        return float("nan")
    pressure_term = (gamma_electron * charge_state * max(te_ev, 0.0)
                     + gamma_ion * max(ti_ev, 0.0)) * Q_E
    return float(np.sqrt(pressure_term / ion_mass_kg))


def ion_inertial_length_m(ion_density_per_m3: float, ion_mass_kg: float,
                          charge_state: float = 1.0) -> float:
    """Ion inertial length d_i = c / omega_pi [m]."""
    if ion_density_per_m3 <= 0.0 or ion_mass_kg <= 0.0:
        return float("nan")
    omega_pi = np.sqrt(ion_density_per_m3 * (charge_state * Q_E) ** 2
                       / (EPSILON_0 * ion_mass_kg))
    return float(C_LIGHT_MS / omega_pi)


def ion_gyrofrequency_rad_s(b_tesla: float, ion_mass_kg: float,
                            charge_state: float = 1.0) -> float:
    """Ion cyclotron frequency omega_ci = Z e |B| / m_i [rad/s]."""
    if ion_mass_kg <= 0.0:
        return float("nan")
    return float(charge_state * Q_E * abs(b_tesla) / ion_mass_kg)


def plasma_beta(number_density_per_m3: float, temperature_ev: float,
                b_tesla: float) -> float:
    """Single-species beta = n kT / (B^2 / 2 mu0) [dimensionless]."""
    if b_tesla == 0.0:
        return float("inf")
    magnetic_pressure_pa = b_tesla * b_tesla / (2.0 * MU_0)
    return float(number_density_per_m3 * temperature_ev * Q_E / magnetic_pressure_pa)


def theta_from_ev(temperature_ev: float, mass_kg: float) -> float:
    """Dimensionless temperature theta = kT / (m c^2), i.e. WarpX's ``u_std**2``."""
    return float(temperature_ev * Q_E / (mass_kg * C_LIGHT_MS**2))


def ev_from_theta(theta: float, mass_kg: float) -> float:
    """Inverse of :func:`theta_from_ev`."""
    return float(theta * mass_kg * C_LIGHT_MS**2 / Q_E)


def _safe_ratio(numerator: float, denominator: float) -> float:
    """``numerator/denominator``, returning +-inf rather than raising when it is 0.

    An unmagnetized target (B = 0) gives v_A = 0 and so an infinite Mach number;
    :func:`derive` rejects that with a message about the field, which is far more
    useful than a ZeroDivisionError from deep inside a property.
    """
    if denominator == 0.0:
        return float("inf") if numerator >= 0.0 else float("-inf")
    return float(numerator / denominator)


def cfl_timestep_s(cell_size_m: float, cfl: float, n_dims: int) -> float:
    """Yee-solver CFL step for a square cell: dt = cfl * dx / (c sqrt(n_dims)) [s].

    Reproduces both decks whose dt is printed: 1D dx = 0.5 d_e at cfl 0.75 gives
    dt*omega_pe = 0.375, and 2D dx = 1 d_e at cfl 0.75 gives 0.5303.
    """
    return float(cfl * cell_size_m / (C_LIGHT_MS * np.sqrt(n_dims)))


