def invariance_report(scaling: ReducedScaling, rel_tol: float = 1e-6) -> str:
    """A FLASH-vs-deck table of the matched invariants and the broken ones.

    ``rel_tol`` only controls the OK/OFF marker; the numbers are always printed, so a
    mismatch stays visible even when it is intentional (a hand-tuned theta_e that
    moves M_A, say).
    """
    targets = scaling.targets
    if targets is None:
        raise ValueError("invariance_report needs the FLASH targets")

    want, got = targets.invariants(), scaling.invariants()
    lines = ["Matched dimensionless invariants (FLASH -> deck)",
             f"  {'quantity':<18} {'FLASH':>12} {'deck':>12}  {'rel err':>9}"]
    for key, flash_value in want.items():
        deck_value = got[key]
        rel_err = (abs(deck_value - flash_value) / abs(flash_value)
                   if flash_value != 0.0 and np.isfinite(flash_value) else float("nan"))
        mark = "" if not np.isfinite(rel_err) or rel_err <= rel_tol else "   <-- OFF"
        lines.append(f"  {key:<18} {flash_value:>12.4g} {deck_value:>12.4g}  "
                     f"{rel_err:>9.2e}{mark}")

    flash_mass_ratio = targets.a_amb * M_P_KG / M_E_KG
    flash_wpe_over_wci = plasma_frequency_rad_s(targets.n_amb_per_m3) / targets.omega_ci_rad_s
    deck_wpe_over_wci = scaling.omega_pe_rad_s * scaling.gyroperiod_s / (2.0 * np.pi)
    rows = [
        ("m_i/m_e", flash_mass_ratio, scaling.mass_ratio),
        ("Z_ambient", targets.z_amb, 1.0),
        ("omega_pe/omega_ci", flash_wpe_over_wci, deck_wpe_over_wci),
        ("v_piston/c", targets.v_front_ms / C_LIGHT_MS, scaling.v_piston_c),
        ("n_ambient [m^-3]", targets.n_amb_per_m3, scaling.n0_per_m3),
        ("B_ambient [T]", targets.b_amb_tesla, scaling.b0_tesla),
        ("d_i [m]", targets.d_i_m, scaling.d_i_m),
        ("T_ci [s]", targets.gyroperiod_s, scaling.gyroperiod_s),
        # The slab is the piston reservoir, not the measured e-folding length; the deck
        # cannot and does not claim to reproduce the latter.
        ("L_piston/d_i", targets.l_piston_di, scaling.slab_halfwidth_di),
    ]
    lines += ["",
              "Deliberately NOT matched (reduced-mass PIC; see the module docstring)",
              f"  {'quantity':<18} {'FLASH':>12} {'deck':>12}"]
    lines += [f"  {name:<18} {flash_value:>12.4g} {deck_value:>12.4g}"
              for name, flash_value, deck_value in rows]
    return "\n".join(lines)
